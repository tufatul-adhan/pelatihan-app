-- PostgreSQL schema for the training service backend.
-- Create DB_NAME first (npm run db:setup handles that), then run this file.

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'user' CHECK (role IN ('admin', 'user')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_users_role ON users(role);

CREATE TABLE IF NOT EXISTS pelatihan (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_pelatihan VARCHAR(255) NOT NULL,
  deskripsi TEXT NOT NULL,
  harga NUMERIC(12, 2) NOT NULL CHECK (harga >= 0),
  duration VARCHAR(120),
  tanggal TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_pelatihan_tanggal ON pelatihan(tanggal);
CREATE INDEX IF NOT EXISTS idx_pelatihan_harga ON pelatihan(harga);

CREATE TABLE IF NOT EXISTS permintaan (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  pelatihan_id INTEGER NOT NULL REFERENCES pelatihan(id) ON DELETE CASCADE,
  jumlah_peserta INTEGER NOT NULL CHECK (jumlah_peserta > 0),
  deskripsi TEXT,
  status VARCHAR(20) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'diproses', 'ditolak', 'selesai')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_permintaan_user_id ON permintaan(user_id);
CREATE INDEX IF NOT EXISTS idx_permintaan_pelatihan_id ON permintaan(pelatihan_id);
CREATE INDEX IF NOT EXISTS idx_permintaan_status ON permintaan(status);
CREATE INDEX IF NOT EXISTS idx_permintaan_created_at ON permintaan(created_at);
